// Validates data/devices.json and embeds it into src/data.generated.ts,
// so the compiled package works in Node and bundlers without JSON import attributes.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dataPath = path.join(root, 'data/devices.json')
const outPath = path.join(root, 'src/data.generated.ts')

const DEVICE_TYPES = new Set(['phone', 'tablet'])
const normalize = (value) => value.toLowerCase().replace(/\+/g, 'plus').replace(/[^a-z0-9]/g, '')

const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'))
const errors = []

if (!/^\d{4}-\d{2}-\d{2}$/.test(data.updatedAt ?? '')) {
  errors.push('updatedAt must be a YYYY-MM-DD date')
}
if (!Array.isArray(data.brands) || data.brands.length === 0) {
  errors.push('brands must be a non-empty array')
}

const brandNames = new Set()
const globalKeys = new Map()

for (const brand of data.brands ?? []) {
  const brandName = brand.name?.trim()
  if (!brandName) {
    errors.push('brand without a name')
    continue
  }
  if (brandNames.has(normalize(brandName))) errors.push(`duplicate brand: ${brandName}`)
  brandNames.add(normalize(brandName))

  if (!Array.isArray(brand.notes) || brand.notes.some((note) => typeof note !== 'string' || !note.trim())) {
    errors.push(`${brandName}: notes must be an array of non-empty strings`)
  }
  if (!Array.isArray(brand.devices) || brand.devices.length === 0) {
    errors.push(`${brandName}: devices must be a non-empty array`)
    continue
  }

  for (const device of brand.devices) {
    const label = `${brandName} / ${device.model}`
    if (typeof device.model !== 'string' || !device.model.trim() || device.model !== device.model.trim()) {
      errors.push(`${label}: model must be a trimmed non-empty string`)
      continue
    }
    if (!DEVICE_TYPES.has(device.type)) errors.push(`${label}: type must be one of ${[...DEVICE_TYPES].join(', ')}`)
    if (device.aliases !== undefined && (!Array.isArray(device.aliases) || device.aliases.some((alias) => typeof alias !== 'string' || !alias.trim()))) {
      errors.push(`${label}: aliases must be an array of non-empty strings`)
    }
    const extraKeys = Object.keys(device).filter((key) => !['model', 'type', 'aliases'].includes(key))
    if (extraKeys.length) errors.push(`${label}: unknown fields ${extraKeys.join(', ')}`)

    // Every name must resolve to exactly one device, otherwise lookups become ambiguous.
    for (const name of [device.model, ...(device.aliases ?? [])]) {
      const key = normalize(name)
      const owner = globalKeys.get(key)
      if (owner && owner !== label) errors.push(`"${name}" (${label}) collides with ${owner}`)
      globalKeys.set(key, label)
    }
  }
}

if (errors.length) {
  console.error(`data/devices.json is invalid:\n- ${errors.join('\n- ')}`)
  process.exit(1)
}

const { $schema, ...payload } = data
fs.writeFileSync(
  outPath,
  `// Generated by scripts/generate.mjs from data/devices.json. Do not edit.\n` +
    `import type { DeviceData } from './types.js'\n\n` +
    `export const data: DeviceData = ${JSON.stringify(payload, null, 2)}\n`
)

const deviceCount = data.brands.reduce((sum, brand) => sum + brand.devices.length, 0)
console.log(`devices.json OK: ${data.brands.length} brands, ${deviceCount} devices`)
